test("the committed dashboard is generated byte-for-byte from its source parts", (t) => {
  assert.ok(composeDashboard, "composer import must succeed before contract assertions run");

  const { output, sha256, partCount } = composeDashboard({ sourceRoot: dashboardSourceRoot });
  const repeated = composeDashboard({ sourceRoot: dashboardSourceRoot });
  const committedOutput = fs.readFileSync(dashboardOutputPath);
  assert.deepEqual(output, committedOutput);
  assert.deepEqual(repeated.output, output, "composition is deterministic across repeated runs");
  assert.equal(output.length, 207976);
  assert.equal(sha256, baselineSha256);
  assert.equal(crypto.createHash("sha256").update(committedOutput).digest("hex"), baselineSha256);
  assert.equal(partCount, 17);

  const expectedDocument = new JSDOM(committedOutput.toString("utf8")).window.document;
  const generatedDocument = new JSDOM(output.toString("utf8")).window.document;
  assert.equal(generatedDocument.documentElement.outerHTML, expectedDocument.documentElement.outerHTML);
  assert.deepEqual(
    [...generatedDocument.querySelectorAll(".sidebar [data-app-view]")].map((item) =>
      item.getAttribute("data-app-view"),
    ),
    expectedRoutes,
  );
  const ids = [...generatedDocument.querySelectorAll("[id]")].map((element) => element.id);
  assert.equal(ids.length, 581);
  assert.equal(new Set(ids).size, 581, "the reviewed document has no duplicate IDs");
  assert.equal(generatedDocument.querySelectorAll("form").length, 15);
  assert.equal(generatedDocument.querySelectorAll('[role="dialog"]').length, 5);
  assert.deepEqual(
    [...generatedDocument.querySelectorAll('link[rel="stylesheet"]')].map((link) =>
      link.getAttribute("href"),
    ),
    ["/app/style.css?v=ui-linear-dashboard-9", "/brand/brand-logo.css", "/app/vendor/fullcalendar.css"],
  );
  assert.deepEqual(
    [...generatedDocument.querySelectorAll("script[src]")].map((script) =>
      script.getAttribute("src"),
    ),
    [
      "/app/theme-init.js",
      "/brand/brand-logo.js",
      "/config.js",
      "/app/vendor/fullcalendar.min.js",
      "/app/vendor/dompurify.min.js",
      "/app/vendor/i18next.min.js",
      "/i18n-client.js?v=ui-linear-dashboard-2",
      "/app/dialog-focus.js",
      "/app/dashboard-router.js?v=1",
      "/app/dashboard-shared.js",
      "/app/dashboard-inbox.js",
      "/app/dashboard-ai-settings.js",
      "/app/dashboard-settings.js",
      "/app/dashboard-integrations.js",
      "/app/dashboard-overview.js",
      "/app/dashboard-reviews.js",
      "/app/dashboard-knowledge.js",
      "/app/dashboard-team.js",
      "/app/dashboard-ai-simulator.js",
      "/app/dashboard-bookings.js",
      "/app/dashboard-auth-transport.js",
      "/app/app.js?v=ui-linear-dashboard-2",
      "/app/mfa.js?v=phase3-auth-mfa-1",
    ],
  );
});

function createFixture({ entry, parts = {}, extraFiles = {}, declaredParts, includeSuffix = true }) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "dashboard-composition-"));
  const envelope = { prefix: "<!doctype html>\n", suffix: "</html>\n" };
  fs.mkdirSync(path.join(root, "partials"), { recursive: true });
  fs.writeFileSync(
    path.join(root, "index.html"),
    `${envelope.prefix}${entry}${includeSuffix ? envelope.suffix : ""}`,
    "utf8",
  );
  for (const [relativePath, content] of Object.entries(parts)) {
    const filePath = path.join(root, relativePath);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content, "utf8");
  }
  for (const [relativePath, content] of Object.entries(extraFiles)) {
    const filePath = path.join(root, relativePath);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content, "utf8");
  }
  fs.writeFileSync(
    path.join(root, "manifest.json"),
    `${JSON.stringify({ entry: "index.html", envelope, parts: declaredParts || Object.keys(parts) }, null, 2)}\n`,
    "utf8",
  );
  return root;
}

function withFixture(options, callback) {
  const root = createFixture(options);
  try {
    return callback(root);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

test("the composer rejects missing files, duplicate references, and incomplete markers", () => {
  withFixture(
    {
      entry: '<!-- @dashboard-include partials/missing.html -->\n',
      parts: {},
      declaredParts: ["partials/missing.html"],
    },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /source tree does not match/),
  );

  withFixture(
    {
      entry: [
        "<!-- @dashboard-include partials/a.html -->",
        "<!-- @dashboard-include partials/a.html -->",
        "",
      ].join("\n"),
      parts: { "partials/a.html": "<p>one</p>\n" },
    },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /duplicate include reference/),
  );

  withFixture(
    { entry: "<!-- @dashboard-include partials/a.html\n", parts: { "partials/a.html": "<p>one</p>\n" } },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /malformed include marker/),
  );
});

test("the composer rejects truncated documents before writing output", () => {
  withFixture(
    {
      entry: "<main>complete body</main>\n",
      parts: {},
      includeSuffix: false,
    },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /declared document envelope/),
  );

  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "dashboard-composition-cli-"));
  const outputPath = path.join(temporaryDirectory, "sentinel.html");
  const originalOutput = "preserve this output\n";
  try {
    fs.writeFileSync(outputPath, originalOutput, "utf8");
    const result = childProcess.spawnSync(
      process.execPath,
      [path.join(repositoryRoot, "web/scripts/compose-dashboard.mjs"), "--output", outputPath, "--chek"],
      { cwd: repositoryRoot, encoding: "utf8" },
    );
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /unknown or trailing arguments/);
    assert.equal(fs.readFileSync(outputPath, "utf8"), originalOutput);
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
  }
});

test("--check rejects output drift without modifying the committed output", () => {
  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "dashboard-composition-drift-"));
  const temporaryWebRoot = path.join(temporaryDirectory, "web");
  fs.mkdirSync(path.join(temporaryWebRoot, "scripts"), { recursive: true });
  fs.cpSync(dashboardSourceRoot, path.join(temporaryWebRoot, "dashboard-src"), { recursive: true });
  fs.copyFileSync(
    path.join(repositoryRoot, "web/scripts/compose-dashboard.mjs"),
    path.join(temporaryWebRoot, "scripts/compose-dashboard.mjs"),
  );
  const driftedOutput = Buffer.from("intentionally drifted output\n");
  const temporaryOutputPath = path.join(temporaryWebRoot, "index.html");
  fs.writeFileSync(temporaryOutputPath, driftedOutput);
  try {
    const result = childProcess.spawnSync(
      process.execPath,
      [path.join(temporaryWebRoot, "scripts/compose-dashboard.mjs"), "--check"],
      { cwd: temporaryDirectory, encoding: "utf8" },
    );
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /differs from the committed web\/index.html/);
    assert.deepEqual(fs.readFileSync(temporaryOutputPath), driftedOutput);
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
  }
});

test("the composer rejects traversal, cycles, and undeclared source files", () => {
  withFixture(
    {
      entry: "<!-- @dashboard-include partials/../outside.html -->\n",
      parts: { "partials/a.html": "<p>one</p>\n" },
    },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /not an allowed relative HTML path/),
  );

  withFixture(
    {
      entry: "<!-- @dashboard-include partials/a.html -->\n",
      parts: {
        "partials/a.html": "<!-- @dashboard-include partials/b.html -->\n",
        "partials/b.html": "<!-- @dashboard-include partials/a.html -->\n",
      },
    },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /include cycle detected/),
  );

  withFixture(
    {
      entry: "<!-- @dashboard-include partials/a.html -->\n",
      parts: { "partials/a.html": "<p>one</p>\n" },
      extraFiles: { "partials/unused.html": "<p>unused</p>\n" },
    },
    (root) => assert.throws(() => composeDashboard({ sourceRoot: root }), /source tree does not match/),
  );
});

test("the composer rejects symlinked source trees", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "dashboard-composition-link-"));
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), "dashboard-composition-outside-"));
  try {
    fs.writeFileSync(path.join(root, "index.html"), "<!-- @dashboard-include partials/a.html -->\n", "utf8");
    fs.writeFileSync(
      path.join(root, "manifest.json"),
      JSON.stringify({
        entry: "index.html",
        envelope: { prefix: "<!doctype html>\n", suffix: "</html>\n" },
        parts: ["partials/a.html"],
      }),
    );
    const outsidePart = path.join(outside, "a.html");
    fs.writeFileSync(outsidePart, "<p>outside</p>\n", "utf8");
    fs.symlinkSync(outside, path.join(root, "partials"), "junction");
    assert.throws(() => composeDashboard({ sourceRoot: root }), /symbolic links are not allowed/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
    fs.rmSync(outside, { recursive: true, force: true });
  }
});
